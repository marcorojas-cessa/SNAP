function entry = localExpr(name, expression, requiredFeatures, rationale)
    entry = struct();
    entry.name = name;
    entry.expression = localVectorizeOperators(expression);
    entry.requiredFeatures = requiredFeatures;
    entry.rationale = rationale;
end

function exprOut = localVectorizeOperators(exprIn)
    exprOut = char(string(exprIn));
    exprOut = regexprep(exprOut, '(?<!\.)\^', '.^');
    exprOut = regexprep(exprOut, '(?<!\.)\*', '.*');
    exprOut = regexprep(exprOut, '(?<!\.)/(?!/)', './');
end

