function pack = buildExpressionPack(varargin)
% buildExpressionPack - Build a per-channel SVM expression pack for SNAP.
%
% This is an example contribution that expands beyond the default
% "all non-position base features" behavior by adding a curated set of
% scientifically motivated custom expressions.
%
% Usage:
%   pack = snap_contrib.svm.buildExpressionPack('ParameterFile', 'params.mat');
%   pack = snap_contrib.svm.buildExpressionPack('ParameterStruct', paramsStruct);
%
% Name-value options:
%   'ParameterFile'                - SNAP parameter MAT file
%   'ParameterStruct'              - already-loaded parameter struct
%   'Channels'                     - channel indices to include (default: all)
%   'IncludeAdvancedStatsFeatures' - include model-selection/statistical
%                                    base features produced by
%                                    snap_contrib.svm.augmentFitResultsWithModelStats
%   'SelectionMode'                - base-feature selection strategy:
%                                      'focused' (default): prioritized compact subset
%                                      'all_non_position': all non-position features
%
% Output:
%   pack - struct with per-channel selectedFeatures/customExpressions.

    p = inputParser;
    p.addParameter('ParameterFile', '', @(x) ischar(x) || isstring(x));
    p.addParameter('ParameterStruct', struct(), @isstruct);
    p.addParameter('Channels', [], @(x) isempty(x) || (isnumeric(x) && isvector(x)));
    p.addParameter('IncludeAdvancedStatsFeatures', false, @(x) islogical(x) || isnumeric(x));
    p.addParameter('SelectionMode', 'focused', @(x) ischar(x) || isstring(x));
    p.parse(varargin{:});
    opts = p.Results;
    selectionMode = lower(strtrim(char(string(opts.SelectionMode))));
    if ~ismember(selectionMode, {'focused', 'all_non_position'})
        error('buildExpressionPack:InvalidSelectionMode', ...
            'SelectionMode must be ''focused'' or ''all_non_position''.');
    end

    params = opts.ParameterStruct;
    parameterSource = 'ParameterStruct';

    if isempty(fieldnames(params))
        parameterFile = strtrim(char(string(opts.ParameterFile)));
        if isempty(parameterFile)
            error('buildExpressionPack:MissingParameters', ...
                'Provide either ParameterStruct or ParameterFile.');
        end
        [params, meta] = snap_helpers.classification.loadParameterStruct(parameterFile);
        parameterSource = parameterFile;
    else
        [params, meta] = snap_helpers.classification.loadParameterStruct(params);
    end

    [allCaps, capMeta] = snap_helpers.classification.resolveChannelCapabilities(params, ...
        'IncludeFeatureInfo', true, ...
        'HasPhysicalSpacing', false);
    numChannels = numel(allCaps);

    channels = [allCaps.channelIdx];
    if ~isempty(opts.Channels)
        channels = unique(round(opts.Channels(:)'));
        channels = channels(channels >= 1 & channels <= numChannels);
        if isempty(channels)
            error('buildExpressionPack:InvalidChannels', ...
                'No valid channels selected. Valid range is 1..%d.', numChannels);
        end
    end

    includeAdvanced = logical(opts.IncludeAdvancedStatsFeatures);
    advancedStatsFeatures = localAdvancedStatsFeatureNames();
    exprLibrary = localExpressionLibrary();

    channelPacks = repmat(struct( ...
        'channelIdx', 1, ...
        'fittingMethod', '', ...
        'has3D', true, ...
        'selectedFeatures', {{}}, ...
        'customExpressions', struct('name', {}, 'expression', {}, 'requiredFeatures', {}, 'requiredCapabilities', {}), ...
        'requiredFeatures', {{}}, ...
        'requiredCapabilities', struct('fittingMethod', '', 'has3D', [], 'hasPhysicalSpacing', []), ...
        'advancedStatsFeatureNames', {{}}, ...
        'notes', ''), 1, numel(channels));

    for i = 1:numel(channels)
        ch = channels(i);
        capIdx = find([allCaps.channelIdx] == ch, 1, 'first');
        if isempty(capIdx)
            error('buildExpressionPack:ChannelResolutionError', ...
                'Could not resolve feature capabilities for channel %d.', ch);
        end

        cap = allCaps(capIdx);
        allFeatures = cap.availableFeatures;
        featureInfo = cap.featureInfo;
        fittingMethod = cap.fittingMethod;
        has3D = logical(cap.has3D);

        selected = localSelectBaseFeatures(allFeatures, featureInfo, fittingMethod, has3D, selectionMode);
        if includeAdvanced
            selected = unique([selected, advancedStatsFeatures], 'stable');
        end

        availableSet = unique([allFeatures, selected], 'stable');
        customExpressions = localSelectExpressions(exprLibrary, availableSet, fittingMethod, has3D);
        requiredFeatures = unique([selected, localCollectExpressionRequiredFeatures(customExpressions)], 'stable');

        channelPacks(i).channelIdx = ch;
        channelPacks(i).fittingMethod = fittingMethod;
        channelPacks(i).has3D = has3D;
        channelPacks(i).selectedFeatures = selected;
        channelPacks(i).customExpressions = customExpressions;
        channelPacks(i).requiredFeatures = requiredFeatures;
        channelPacks(i).requiredCapabilities = struct( ...
            'fittingMethod', fittingMethod, ...
            'has3D', has3D, ...
            'hasPhysicalSpacing', false);
        if includeAdvanced
            channelPacks(i).advancedStatsFeatureNames = advancedStatsFeatures;
            channelPacks(i).notes = sprintf([ ...
                'Includes optional model-stat features from ', ...
                'snap_contrib.svm.augmentFitResultsWithModelStats.']);
        else
            channelPacks(i).advancedStatsFeatureNames = {};
            channelPacks(i).notes = 'UI-compatible expression set using canonical SNAP features only.';
        end
    end

    pack = struct();
    pack.specVersion = '2.0.0';
    pack.packId = 'snap_literature_informed_svm_pack';
    pack.minSnapVersion = '1.1.0';
    pack.strictModeDefault = false;
    pack.name = 'SNAP Literature-Informed SVM Expression Pack';
    pack.version = '2.0.0';
    pack.generatedOn = datestr(now, 'yyyy-mm-dd HH:MM:SS');
    pack.parameterSource = parameterSource;
    pack.parameterContainer = meta.container;
    pack.parameterWarnings = meta.warnings;
    pack.numChannelsDetected = numChannels;
    pack.channelsIncluded = channels;
    pack.includeAdvancedStatsFeatures = includeAdvanced;
    pack.selectionMode = selectionMode;
    pack.description = [ ...
        'Example contribution pack with channel-aware curated expressions and ', ...
        'capability metadata for safe validation against SNAP parameter files.'];
    pack.references = localLiteratureReferences();
    pack.channelResolutionMeta = capMeta;
    pack.channelPacks = channelPacks;
    pack.rationale = [ ...
        'Expressions emphasize dynamic-range stabilization (log transforms), ', ...
        'signal-vs-background normalization, PSF/shape compactness, anisotropy, ', ...
        'and fit-quality coupling.'];
end

function selected = localNonPositionFeatures(allFeatures, featureInfo)
    selected = {};
    for i = 1:numel(allFeatures)
        f = allFeatures{i};
        if isfield(featureInfo, f) && isfield(featureInfo.(f), 'category') && ...
                strcmpi(featureInfo.(f).category, 'position')
            continue;
        end
        selected{end+1} = f; %#ok<AGROW>
    end
end

function selected = localSelectBaseFeatures(allFeatures, featureInfo, fittingMethod, has3D, selectionMode)
    if nargin < 5 || isempty(selectionMode)
        selectionMode = 'focused';
    end
    selectionMode = lower(strtrim(char(string(selectionMode))));

    allNonPosition = localNonPositionFeatures(allFeatures, featureInfo);
    if strcmp(selectionMode, 'all_non_position')
        selected = allNonPosition;
        return;
    end

    methodKey = localFocusedProfileKey(fittingMethod, has3D);
    prioritized = localFocusedFeatureProfile(methodKey);
    selected = unique(prioritized, 'stable');
    selected = selected(ismember(selected, allNonPosition));

    if isempty(selected)
        selected = localLegacyFocusedSelection(allFeatures, fittingMethod, has3D);
        selected = unique(selected, 'stable');
        selected = selected(ismember(selected, allNonPosition));
    end

    if isempty(selected)
        selected = allNonPosition;
    end
end

function methodKey = localFocusedProfileKey(fittingMethod, has3D)
    fm = lower(strtrim(char(string(fittingMethod))));

    if contains(fm, 'radial symmetry')
        methodKey = 'radial_symmetry';
        return;
    end
    if contains(fm, '2d (xy) + 1d (z)') || contains(fm, '2d+1d')
        methodKey = 'gaussian_2d_plus_1d';
        return;
    end
    if contains(fm, '1d (x,y,z)') || contains(fm, '1d x,y,z')
        methodKey = 'gaussian_1d_xyz';
        return;
    end
    if contains(fm, 'skewed')
        if has3D
            methodKey = 'skewed_3d';
        else
            methodKey = 'skewed_2d';
        end
        return;
    end
    if contains(fm, 'distorted')
        if has3D
            methodKey = 'distorted_3d';
        else
            methodKey = 'distorted_2d';
        end
        return;
    end
    if contains(fm, '2d gaussian')
        methodKey = 'gaussian_2d';
        return;
    end
    if contains(fm, '3d gaussian')
        methodKey = 'gaussian_3d';
        return;
    end

    if has3D
        methodKey = 'gaussian_3d';
    else
        methodKey = 'gaussian_2d';
    end
end

function prioritized = localFocusedFeatureProfile(methodKey)
    core = {'integrated_intensity', 'background', 'snr'};

    switch methodKey
        case 'distorted_3d'
            % IMPORTANT: keep Distorted 3D focused profile unchanged.
            prioritized = [core, { ...
                'r_squared', 'amplitude', ...
                'sigma_x', 'sigma_y', 'sigma_z', ...
                'sigma_sum', 'sigma_product', 'sigma_xy_ratio', 'sigma_z_ratio', ...
                'amplitude_over_background', ...
                'rho_xy', 'rho_xz', 'rho_yz'}];

        case 'distorted_2d'
            prioritized = [core, { ...
                'r_squared', 'amplitude', ...
                'sigma_x', 'sigma_y', ...
                'sigma_sum', 'sigma_product', 'sigma_xy_ratio', ...
                'amplitude_over_background', 'rho_xy'}];

        case 'skewed_3d'
            prioritized = [core, { ...
                'r_squared', 'amplitude', ...
                'sigma_x', 'sigma_y', 'sigma_z', ...
                'sigma_sum', 'sigma_product', 'sigma_xy_ratio', 'sigma_z_ratio', ...
                'amplitude_over_background', ...
                'rho_xy', 'rho_xz', 'rho_yz', ...
                'alpha_x', 'alpha_y', 'alpha_z'}];

        case 'skewed_2d'
            prioritized = [core, { ...
                'r_squared', 'amplitude', ...
                'sigma_x', 'sigma_y', ...
                'sigma_sum', 'sigma_product', 'sigma_xy_ratio', ...
                'amplitude_over_background', ...
                'alpha_x', 'alpha_y'}];

        case 'gaussian_3d'
            prioritized = [core, { ...
                'r_squared', 'amplitude', ...
                'sigma_x', 'sigma_y', 'sigma_z', ...
                'sigma_sum', 'sigma_product', 'sigma_xy_ratio', 'sigma_z_ratio', ...
                'amplitude_over_background'}];

        case 'gaussian_2d'
            prioritized = [core, { ...
                'r_squared', 'amplitude', ...
                'sigma_x', 'sigma_y', ...
                'sigma_sum', 'sigma_product', 'sigma_xy_ratio', ...
                'amplitude_over_background'}];

        case 'gaussian_1d_xyz'
            prioritized = [core, { ...
                'r_squared', 'amplitude', ...
                'amplitude_x', 'amplitude_y', 'amplitude_z', ...
                'sigma_x', 'sigma_y', 'sigma_z', ...
                'sigma_sum', 'sigma_product', 'sigma_xy_ratio', 'sigma_z_ratio'}];

        case 'gaussian_2d_plus_1d'
            prioritized = [core, { ...
                'r_squared', ...
                'amplitude_xy', 'amplitude_z', ...
                'sigma_x', 'sigma_y', 'sigma_z', ...
                'sigma_sum', 'sigma_product', 'sigma_xy_ratio', 'sigma_z_ratio'}];

        case 'radial_symmetry'
            prioritized = [core, {'radial_symmetry_score'}];

        otherwise
            prioritized = {};
    end
end

function prioritized = localLegacyFocusedSelection(allFeatures, fittingMethod, has3D)
    prioritized = {};

    if ismember('integrated_intensity', allFeatures)
        prioritized{end+1} = 'integrated_intensity'; %#ok<AGROW>
    end
    if ismember('background', allFeatures)
        prioritized{end+1} = 'background'; %#ok<AGROW>
    end
    if ismember('snr', allFeatures)
        prioritized{end+1} = 'snr'; %#ok<AGROW>
    end

    if ismember('r_squared', allFeatures)
        prioritized{end+1} = 'r_squared'; %#ok<AGROW>
    elseif ismember('radial_symmetry_score', allFeatures)
        prioritized{end+1} = 'radial_symmetry_score'; %#ok<AGROW>
    end

    amplitudeCandidates = {'amplitude', 'amplitude_xy', 'amplitude_z', 'amplitude_x', 'amplitude_y'};
    for i = 1:numel(amplitudeCandidates)
        if ismember(amplitudeCandidates{i}, allFeatures)
            prioritized{end+1} = amplitudeCandidates{i}; %#ok<AGROW>
        end
    end

    sigmaCandidates = {'sigma_x', 'sigma_y', 'sigma_z', 'sigma_sum', 'sigma_product', 'sigma_xy_ratio', 'sigma_z_ratio'};
    for i = 1:numel(sigmaCandidates)
        if ismember(sigmaCandidates{i}, allFeatures)
            prioritized{end+1} = sigmaCandidates{i}; %#ok<AGROW>
        end
    end

    if ismember('amplitude_over_background', allFeatures)
        prioritized{end+1} = 'amplitude_over_background'; %#ok<AGROW>
    end

    if contains(lower(fittingMethod), 'distorted') || contains(lower(fittingMethod), 'skewed')
        rhoCandidates = {'rho_xy', 'rho_xz', 'rho_yz'};
        for i = 1:numel(rhoCandidates)
            if ismember(rhoCandidates{i}, allFeatures)
                prioritized{end+1} = rhoCandidates{i}; %#ok<AGROW>
            end
        end
    end

    if has3D && ismember('sigma_z', allFeatures) && ~ismember('sigma_z', prioritized)
        prioritized{end+1} = 'sigma_z'; %#ok<AGROW>
    end
end

function expressions = localSelectExpressions(exprLibrary, availableFeatures, fittingMethod, has3D)
    if isempty(exprLibrary)
        expressions = struct('name', {}, 'expression', {}, 'requiredFeatures', {}, 'requiredCapabilities', {});
        return;
    end

    availableSet = string(availableFeatures);
    expressions = struct('name', {}, 'expression', {}, 'requiredFeatures', {}, 'requiredCapabilities', {});
    addedNames = strings(0, 1);

    for i = 1:numel(exprLibrary)
        req = string(exprLibrary(i).requiredFeatures);
        if ~all(ismember(req, availableSet))
            continue;
        end

        exprName = string(exprLibrary(i).name);
        if any(exprName == addedNames)
            continue;
        end

        expressions(end+1) = struct( ... %#ok<AGROW>
            'name', char(exprLibrary(i).name), ...
            'expression', char(exprLibrary(i).expression), ...
            'requiredFeatures', {cellstr(string(exprLibrary(i).requiredFeatures(:)'))}, ...
            'requiredCapabilities', struct('fittingMethod', fittingMethod, 'has3D', logical(has3D)));
        addedNames(end+1, 1) = exprName; %#ok<AGROW>
    end
end

function requiredFeatures = localCollectExpressionRequiredFeatures(customExpressions)
    requiredFeatures = {};
    for i = 1:numel(customExpressions)
        if isfield(customExpressions(i), 'requiredFeatures')
            requiredFeatures = [requiredFeatures, customExpressions(i).requiredFeatures]; %#ok<AGROW>
        end
    end
    requiredFeatures = unique(requiredFeatures, 'stable');
end

function names = localAdvancedStatsFeatureNames()
    names = snap_helpers.classification.getModelStatsFeatureNames();
end

function lib = localExpressionLibrary()
    lib = struct('name', {}, 'expression', {}, 'requiredFeatures', {}, 'rationale', {});

    % Signal/background transforms (dynamic-range stabilized)
    lib(end+1) = localExpr('log_integrated_intensity', ...
        'log10(max(integrated_intensity + 1, 1e-6))', ...
        {'integrated_intensity'}, ...
        'Stabilizes heavy-tailed spot intensity distributions.');
    lib(end+1) = localExpr('log_background', ...
        'log10(max(background + 1, 1e-6))', ...
        {'background'}, ...
        'Compresses local background dynamic range.');
    lib(end+1) = localExpr('log_snr_proxy', ...
        'log10(max((integrated_intensity + 1) / (background + 1), 1e-6))', ...
        {'integrated_intensity', 'background'}, ...
        'Background-normalized signal proxy with log compression.');
    lib(end+1) = localExpr('poisson_snr_proxy', ...
        '(integrated_intensity - background) / sqrt(max(integrated_intensity + background, 1))', ...
        {'integrated_intensity', 'background'}, ...
        'Poisson-like contrast proxy using signal+background variance scaling.');
    lib(end+1) = localExpr('shot_noise_proxy', ...
        '(integrated_intensity - background) / sqrt(max(background, 0) + 1)', ...
        {'integrated_intensity', 'background'}, ...
        'Approximate Poisson-dominated contrast score.');
    lib(end+1) = localExpr('background_fraction', ...
        'background / (integrated_intensity + background + 1)', ...
        {'integrated_intensity', 'background'}, ...
        'Fraction of local intensity explained by background.');
    lib(end+1) = localExpr('signal_fraction', ...
        'integrated_intensity / (integrated_intensity + background + 1)', ...
        {'integrated_intensity', 'background'}, ...
        'Fraction of total local intensity assigned to spot signal.');
    lib(end+1) = localExpr('contrast_to_background', ...
        '(integrated_intensity - background) / (background + 1)', ...
        {'integrated_intensity', 'background'}, ...
        'Classical local contrast ratio.');
    lib(end+1) = localExpr('background_subtracted_log_signal', ...
        'log10(max(integrated_intensity - background + 1, 1e-6))', ...
        {'integrated_intensity', 'background'}, ...
        'Log-compressed signal after background subtraction.');
    lib(end+1) = localExpr('inverse_bg_penalty', ...
        'integrated_intensity / ((background + 1)^2)', ...
        {'integrated_intensity', 'background'}, ...
        'Intensity penalized quadratically by background burden.');

    % Fit-quality couplings
    lib(end+1) = localExpr('quality_weighted_snr', ...
        'r_squared * log10(max((integrated_intensity + 1) / (background + 1), 1e-6))', ...
        {'r_squared', 'integrated_intensity', 'background'}, ...
        'Couples fit quality and normalized signal strength.');
    lib(end+1) = localExpr('quality_penalty', ...
        '(1 - r_squared) * log10(max(integrated_intensity + 1, 1e-6))', ...
        {'r_squared', 'integrated_intensity'}, ...
        'Penalizes bright but poorly fit detections.');
    lib(end+1) = localExpr('quality_bg_compound', ...
        'r_squared * (integrated_intensity / (background + 1))', ...
        {'r_squared', 'integrated_intensity', 'background'}, ...
        'High when both fit quality and background-normalized intensity are high.');
    lib(end+1) = localExpr('quality_vs_size_penalty', ...
        'r_squared / (sigma_sum + 1e-3)', ...
        {'r_squared', 'sigma_sum'}, ...
        'Rewards compact, high-quality fits.');
    lib(end+1) = localExpr('snr_vs_size_penalty', ...
        'snr / (sigma_sum + 1e-3)', ...
        {'snr', 'sigma_sum'}, ...
        'SNR penalized by broad spatial footprint.');
    lib(end+1) = localExpr('snr_quality_harmonic', ...
        '2 / ((1 / max(snr, 1e-3)) + (1 / max(r_squared, 1e-3)))', ...
        {'snr', 'r_squared'}, ...
        'Harmonic coupling of SNR and fit quality (penalizes imbalance).');
    lib(end+1) = localExpr('quality_bg_penalty', ...
        'r_squared / (background + 1)', ...
        {'r_squared', 'background'}, ...
        'Penalizes otherwise good fits in high local background.');
    lib(end+1) = localExpr('quality_signal_fraction', ...
        'r_squared * (integrated_intensity / (integrated_intensity + background + 1))', ...
        {'r_squared', 'integrated_intensity', 'background'}, ...
        'Joint score for fit quality and local signal purity.');
    lib(end+1) = localExpr('quality_signal_harmonic_fraction', ...
        '2 / ((1 / max(r_squared, 1e-3)) + (1 / max(integrated_intensity / (integrated_intensity + background + 1), 1e-3)))', ...
        {'r_squared', 'integrated_intensity', 'background'}, ...
        'Harmonic coupling of fit quality and local signal-purity fraction.');

    % Morphology / compactness descriptors
    lib(end+1) = localExpr('ellipticity_log', ...
        'abs(log(max((abs(sigma_x) + 1e-3) / (abs(sigma_y) + 1e-3), 1e-6)))', ...
        {'sigma_x', 'sigma_y'}, ...
        'Shape anisotropy magnitude in XY.');
    lib(end+1) = localExpr('ellipticity_ratio_xy', ...
        '(abs(sigma_x) + 1e-3) / (abs(sigma_y) + 1e-3)', ...
        {'sigma_x', 'sigma_y'}, ...
        'Raw XY sigma ratio (ellipticity).');
    lib(end+1) = localExpr('psf_roundness_penalty', ...
        'abs(sigma_x - sigma_y) / (sigma_x + sigma_y + 1e-3)', ...
        {'sigma_x', 'sigma_y'}, ...
        'Dimensionless PSF roundness deviation in XY.');
    lib(end+1) = localExpr('psf_roundness_score', ...
        '1 / (1 + abs(sigma_x - sigma_y) / (sigma_x + sigma_y + 1e-3))', ...
        {'sigma_x', 'sigma_y'}, ...
        'Higher when lateral PSF widths are balanced.');
    lib(end+1) = localExpr('compactness_2d', ...
        'integrated_intensity / (sigma_x * sigma_y + 1e-3)', ...
        {'integrated_intensity', 'sigma_x', 'sigma_y'}, ...
        'Intensity concentration per estimated PSF area.');
    lib(end+1) = localExpr('size_penalized_snr_2d', ...
        'log10(max((integrated_intensity + 1) / (background + 1), 1e-6)) / (sigma_x + sigma_y + 1e-3)', ...
        {'integrated_intensity', 'background', 'sigma_x', 'sigma_y'}, ...
        'Normalized signal penalized by broad PSF widths.');
    lib(end+1) = localExpr('quality_per_sigma_sum_2d', ...
        'r_squared / (sigma_x + sigma_y + 1e-3)', ...
        {'r_squared', 'sigma_x', 'sigma_y'}, ...
        'Fit quality normalized by spot footprint.');
    lib(end+1) = localExpr('quality_compactness_coupled_2d', ...
        'r_squared * integrated_intensity / (sigma_x * sigma_y + background + 1)', ...
        {'r_squared', 'integrated_intensity', 'sigma_x', 'sigma_y', 'background'}, ...
        '2D quality-intensity score penalized by spread and local background.');
    lib(end+1) = localExpr('intensity_over_sigma_product', ...
        'integrated_intensity / (sigma_product + 1e-3)', ...
        {'integrated_intensity', 'sigma_product'}, ...
        'Signal concentration using derived sigma-product.');
    lib(end+1) = localExpr('sigma_product_over_intensity', ...
        'sigma_product / (integrated_intensity + 1)', ...
        {'sigma_product', 'integrated_intensity'}, ...
        'Inverse concentration measure; high for diffuse spots.');
    lib(end+1) = localExpr('sigma_sum_over_intensity', ...
        'sigma_sum / (integrated_intensity + 1)', ...
        {'sigma_sum', 'integrated_intensity'}, ...
        'Diffuse-width penalty relative to signal.');
    lib(end+1) = localExpr('thompson_var_xy_proxy', ...
        '(((sigma_x^2 + sigma_y^2) / 2) + (1/12)) / max(integrated_intensity, 1) + (8 * pi * (((sigma_x^2 + sigma_y^2) / 2)^2) * (background^2)) / (max(integrated_intensity, 1)^2)', ...
        {'sigma_x', 'sigma_y', 'integrated_intensity', 'background'}, ...
        'Localization-variance proxy inspired by Thompson et al. (2002).');
    lib(end+1) = localExpr('thompson_precision_xy_proxy', ...
        'sqrt(max(((((sigma_x^2 + sigma_y^2) / 2) + (1/12)) / max(integrated_intensity, 1) + (8 * pi * (((sigma_x^2 + sigma_y^2) / 2)^2) * (background^2)) / (max(integrated_intensity, 1)^2)), 1e-12))', ...
        {'sigma_x', 'sigma_y', 'integrated_intensity', 'background'}, ...
        'Square-root localization precision proxy in XY.');
    lib(end+1) = localExpr('thompson_information_xy', ...
        '1 / (sqrt(max(((((sigma_x^2 + sigma_y^2) / 2) + (1/12)) / max(integrated_intensity, 1) + (8 * pi * (((sigma_x^2 + sigma_y^2) / 2)^2) * (background^2)) / (max(integrated_intensity, 1)^2)), 1e-12)) + 1e-6)', ...
        {'sigma_x', 'sigma_y', 'integrated_intensity', 'background'}, ...
        'Inverse XY precision proxy (higher implies better localization information).');
    lib(end+1) = localExpr('localization_information_density_xy', ...
        '(1 / (sqrt(max(((((sigma_x^2 + sigma_y^2) / 2) + (1/12)) / max(integrated_intensity, 1) + (8 * pi * (((sigma_x^2 + sigma_y^2) / 2)^2) * (background^2)) / (max(integrated_intensity, 1)^2)), 1e-12)) + 1e-6)) / (sigma_x + sigma_y + 1e-3)', ...
        {'sigma_x', 'sigma_y', 'integrated_intensity', 'background'}, ...
        'Localization-information proxy per lateral spread unit.');

    % 3D anisotropy terms
    lib(end+1) = localExpr('compactness_3d', ...
        'integrated_intensity / (sigma_x * sigma_y * sigma_z + 1e-3)', ...
        {'integrated_intensity', 'sigma_x', 'sigma_y', 'sigma_z'}, ...
        'Intensity concentration per estimated PSF volume.');
    lib(end+1) = localExpr('z_anisotropy_abs', ...
        'abs(log(max((abs(sigma_z) + 1e-3) / (((abs(sigma_x) + abs(sigma_y)) / 2) + 1e-3), 1e-6)))', ...
        {'sigma_x', 'sigma_y', 'sigma_z'}, ...
        'Axial-vs-lateral anisotropy magnitude.');
    lib(end+1) = localExpr('size_penalized_snr_3d', ...
        'log10(max((integrated_intensity + 1) / (background + 1), 1e-6)) / (sigma_x + sigma_y + sigma_z + 1e-3)', ...
        {'integrated_intensity', 'background', 'sigma_x', 'sigma_y', 'sigma_z'}, ...
        '3D normalized signal penalized by total width.');
    lib(end+1) = localExpr('sigma_z_compactness', ...
